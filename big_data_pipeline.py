# I am now importing SparkSession which allows me to create a Spark environment in Google Colab
from pyspark.sql import SparkSession

# I am initializing the Spark session with an application name for better tracking
spark = SparkSession.builder \
    .appName("BigDataProcessing_Task3") \
    .getOrCreate()

# Since I have already uploaded the dataset manually into Colab, I am specifying the path here
file_path = "/content/transactions_subset_2000.csv"

# I am now loading the CSV file into a Spark DataFrame while inferring schema and reading the header
df = spark.read.csv(file_path, header=True, inferSchema=True)

# I am printing the schema to verify that the columns are correctly recognized and data types are inferred
df.printSchema()

# I am displaying the first few rows to visually inspect if the data has been loaded correctly
df.show(5)

# Now I am starting the data cleaning phase

# I am dropping rows only where critical columns (YEAR, MONTH, AMOUNT) are missing
# This helps me preserve as much data as possible while ensuring important fields are present
df_clean = df.na.drop(subset=["YEAR", "MONTH", "AMOUNT"])

# I am registering this cleaned dataframe as a temporary SQL view so that I can run Spark SQL queries
df_clean.createOrReplaceTempView("transactions")

# I am running SQL queries to analyze monthly spending trends
spark.sql("""
    SELECT YEAR, MONTH, SUM(AMOUNT) AS monthly_spend
    FROM transactions
    GROUP BY YEAR, MONTH
    ORDER BY YEAR, MONTH
""").show()

# I am analyzing total spend per expense type to understand customer behavior across different categories
spark.sql("""
    SELECT EXP_TYPE, COUNT(*) AS num_transactions, SUM(AMOUNT) AS total_amount
    FROM transactions
    GROUP BY EXP_TYPE
    ORDER BY total_amount DESC
""").show()

# I am identifying the top 5 customers based on their total spending
spark.sql("""
    SELECT CUST_ID, SUM(AMOUNT) AS total_spend
    FROM transactions
    GROUP BY CUST_ID
    ORDER BY total_spend DESC
    LIMIT 5
""").show()

spark.sql("""
    SELECT CUST_ID, SUM(AMOUNT) AS total_spend
    FROM transactions
    GROUP BY CUST_ID
    ORDER BY total_spend DESC
    LIMIT 5
""").show()

# I am importing ML packages needed for feature encoding, modeling, evaluation, and visualization
from pyspark.ml.feature import StringIndexer, VectorAssembler
from pyspark.ml.regression import RandomForestRegressor
from pyspark.ml.evaluation import RegressionEvaluator
from pyspark.ml import Pipeline
import matplotlib.pyplot as plt

# I am preparing the data for machine learning

# First, I am encoding the EXP_TYPE column into numerical format using StringIndexer
indexer = StringIndexer(inputCol="EXP_TYPE", outputCol="EXP_TYPE_INDEX")

# Next, I am assembling all features into a single feature vector
assembler = VectorAssembler(
    inputCols=["YEAR", "MONTH", "DAY", "EXP_TYPE_INDEX"],
    outputCol="features"
)

# I am building a pipeline to apply both the encoding and assembling steps
pipeline = Pipeline(stages=[indexer, assembler])

# I am fitting the pipeline to my cleaned data so it learns the transformation
pipeline_model = pipeline.fit(df_clean)

# I am applying the transformations to the dataset to create the final dataset ready for ML
df_ml = pipeline_model.transform(df_clean)

# I am displaying some sample rows to ensure features are correctly generated
df_ml.select("features", "AMOUNT").show(5, truncate=False)

# Now I am splitting my data into training and testing subsets
# This allows me to evaluate the model on unseen data to check how well it generalizes
train_data, test_data = df_ml.randomSplit([0.8, 0.2], seed=42)

# I am now initializing the RandomForestRegressor with 50 trees
# Random Forest is a very strong model for structured tabular data like this
rf = RandomForestRegressor(featuresCol="features", labelCol="AMOUNT", numTrees=50)

# I am training (fitting) the model on the training dataset
rf_model = rf.fit(train_data)

# After training, I am applying the model to predict on the test data
predictions = rf_model.transform(test_data)

# I am displaying some prediction results to get a quick sense of model output
predictions.select("features", "AMOUNT", "prediction").show(5)

# I am now evaluating model performance using RMSE (Root Mean Squared Error)
# RMSE tells me how far my predictions deviate from actual amounts on average
evaluator = RegressionEvaluator(
    labelCol="AMOUNT", predictionCol="prediction", metricName="rmse"
)
rmse = evaluator.evaluate(predictions)
print(f"Root Mean Squared Error (RMSE): {rmse}")

# I am also calculating R2 score to understand how much variance is explained by my model
r2 = evaluator.evaluate(predictions, {evaluator.metricName: "r2"})
print(f"R-squared (R2): {r2}")

# Finally, I am visualizing the feature importances to understand which features impact predictions the most

# Extract feature importances from the trained model
importances = rf_model.featureImportances.toArray()

# Create a bar plot to visualize feature importances
plt.figure(figsize=(6, 4))
plt.bar(["YEAR", "MONTH", "DAY", "EXP_TYPE_INDEX"], importances)
plt.title("Feature Importance")
plt.xlabel("Features")
plt.ylabel("Importance")
plt.show()

